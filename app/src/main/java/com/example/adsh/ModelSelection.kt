package com.example.adsh

data class ModelRoute(val provider: String, val model: String) {
    init {
        require(provider.isNotBlank() && model.isNotBlank() &&
            provider.none { it.isISOControl() } && model.none { it.isISOControl() }) {
            "模型路由无效"
        }
    }

    fun encode(): String = "$provider\n$model"

    companion object {
        fun decode(value: String): ModelRoute {
            val separator = value.indexOf('\n')
            require(separator > 0 && separator == value.lastIndexOf('\n')) { "模型路由事件无效" }
            return ModelRoute(value.substring(0, separator), value.substring(separator + 1))
        }
    }
}

fun selectedModel(events: List<SessionEventRow>, fallback: ModelRoute): ModelRoute =
    events.lastOrNull { it.type == "model/selection" }?.let { ModelRoute.decode(it.data) } ?: fallback

fun shouldRecordModelSelection(events: List<SessionEventRow>, selected: ModelRoute): Boolean =
    events.lastOrNull { it.type == "model/selection" }
        ?.let { ModelRoute.decode(it.data) != selected } ?: true

fun modelChangeNotice(previous: ModelRoute?, selected: ModelRoute): String? {
    if (previous == null || previous == selected) return null
    val from = if (previous.provider == selected.provider) previous.model else "${previous.provider}/${previous.model}"
    val to = if (previous.provider == selected.provider) selected.model else "${selected.provider}/${selected.model}"
    return "[model changed: assistant turns above this point were generated by $from; " +
        "the session continues with $to]"
}
