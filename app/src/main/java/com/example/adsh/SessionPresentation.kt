package com.example.adsh

data class SessionSummary(
    val id: String,
    val preview: String,
    val eventCount: Int,
    val lastEventTime: Long,
    val workspaceId: String = WorkspaceStore.DEFAULT_ID,
)

fun eventLabel(type: String): String = when (type) {
    "user/message" -> "你"
    "assistant/message" -> "助手"
    "assistant/attempt" -> "失败尝试"
    "model/selection" -> "模型已选择"
    "tool/call" -> "工具调用"
    "tool/result" -> "工具结果"
    "turn/start" -> "回合开始"
    "turn/end" -> "回合结束"
    "step/start" -> "步骤开始"
    "step/end" -> "步骤结束"
    else -> type
}

private val modelChangePattern = Regex(
    "^\\[model changed: assistant turns above this point were generated by ([^;]+); " +
        "the session continues with ([^\\]]+)]$",
)

fun presentEventContent(type: String, data: String): String {
    if (type != "user/message") return data
    val match = modelChangePattern.matchEntire(data) ?: return data
    return "模型已从 ${match.groupValues[1]} 切换为 ${match.groupValues[2]}；之前的回复来自旧模型。"
}

fun summarize(
    id: String,
    events: List<SessionEventRow>,
    workspaceId: String = WorkspaceStore.DEFAULT_ID,
): SessionSummary {
    val first = events.firstOrNull { it.type == "user/message" }?.data.orEmpty()
    return SessionSummary(id, first.replace('\n', ' ').take(80),
        events.size, events.lastOrNull()?.time ?: 0L, workspaceId)
}
