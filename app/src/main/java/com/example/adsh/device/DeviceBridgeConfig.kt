package com.example.adsh.device

import java.io.File

/**
 * Builds the `--patch` overlay that mounts the loopback device bridge through
 * the bundled `@deepseek-ai/dsh-mcp-client`. Kept free of Android types so the
 * generated YAML can be unit tested.
 */
object DeviceBridgeConfig {
    const val SERVER_NAME = "adsh_device"
    const val PATCH_FILE = "android-bridge.cordis.yml"

    fun patchYaml(
        nodePath: String,
        scriptPath: String,
        workingDirectory: String,
        url: String,
        token: String,
    ): String = buildString {
        appendLine("# Generated by the Adsh device bridge; rewritten on every engine start.")
        appendLine("# Revoke by turning the capability bridge off in the app settings.")
        appendLine("- insert:")
        appendLine("    - id: adsh-device-bridge")
        appendLine("      name: '@deepseek-ai/dsh-mcp-client'")
        appendLine("      config:")
        appendLine("        transport: stdio")
        appendLine("        serverName: '$SERVER_NAME'")
        appendLine("        command: ${quote(nodePath)}")
        append("        args:\n")
        appendLine("          - ${quote(scriptPath)}")
        appendLine("        env:")
        appendLine("          ADSH_BRIDGE_URL: ${quote(url)}")
        appendLine("          ADSH_BRIDGE_TOKEN: ${quote(token)}")
        appendLine("        cwd: ${quote(workingDirectory)}")
        appendLine("        toolCallTimeoutMs: 30000")
        appendLine("        failOnStartupError: false")
        appendLine("        reconnect:")
        appendLine("          enabled: true")
        appendLine("          initialDelayMs: 500")
        appendLine("          maxDelayMs: 30000")
        appendLine("          maxAttempts: 5")
    }

    fun writePatch(
        home: File,
        nodePath: String,
        scriptPath: String,
        workingDirectory: String,
        url: String,
        token: String,
    ): File {
        val file = home.resolve(PATCH_FILE)
        file.writeText(
            patchYaml(
                nodePath = nodePath,
                scriptPath = scriptPath,
                workingDirectory = workingDirectory,
                url = url,
                token = token,
            ),
        )
        return file
    }

    private fun quote(value: String): String = "'" + value.replace("'", "''") + "'"
}
