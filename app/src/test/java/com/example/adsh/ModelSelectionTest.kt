package com.example.adsh

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class ModelSelectionTest {
    private val flash = ModelRoute("deepseek-chat-api", "deepseek-flash")
    private val pro = ModelRoute("deepseek-chat-api", "deepseek-v4-pro")
    private fun event(seq: Long, value: String) =
        SessionEventRow("session", seq, "model/selection", 1, value)

    @Test
    fun lastCommittedRouteWinsAndSameRouteNeedsNoEvent() {
        val events = listOf(event(0, flash.encode()), event(1, pro.encode()))
        assertEquals(pro, selectedModel(events, flash))
        assertFalse(shouldRecordModelSelection(events, pro))
        assertTrue(shouldRecordModelSelection(events, flash))
    }

    @Test
    fun legacySessionUsesSelectedDefaultWithoutInventingPastModel() {
        assertEquals(flash, selectedModel(emptyList(), flash))
        assertTrue(shouldRecordModelSelection(emptyList(), flash))
        assertEquals(null, modelChangeNotice(null, flash))
    }

    @Test
    fun switchingAddsModelVisibleNoticeAndRejectsMalformedRoute() {
        assertEquals("[model changed: assistant turns above this point were generated by " +
            "deepseek-flash; the session continues with deepseek-v4-pro]",
            modelChangeNotice(flash, pro))
        assertThrows(IllegalArgumentException::class.java) {
            ModelRoute.decode("deepseek-chat-api\n")
        }
    }
}
