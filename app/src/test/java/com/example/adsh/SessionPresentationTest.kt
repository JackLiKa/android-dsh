package com.example.adsh

import org.junit.Assert.assertEquals
import org.junit.Test

class SessionPresentationTest {
    @Test
    fun modelSwitchNoticeRendersInChineseWithoutChangingLoggedInput() {
        val original = "[model changed: assistant turns above this point were generated by " +
            "deepseek-flash; the session continues with deepseek-v4-pro]"
        assertEquals("模型已从 deepseek-flash 切换为 deepseek-v4-pro；之前的回复来自旧模型。",
            presentEventContent("user/message", original))
        assertEquals(original, presentEventContent("assistant/message", original))
    }

    @Test
    fun eventLabelsKeepDistinctDurableFacts() {
        assertEquals("你", eventLabel("user/message"))
        assertEquals("助手", eventLabel("assistant/message"))
        assertEquals("工具调用", eventLabel("tool/call"))
        assertEquals("工具结果", eventLabel("tool/result"))
        assertEquals("失败尝试", eventLabel("assistant/attempt"))
        assertEquals("custom/event", eventLabel("custom/event"))
    }

    @Test
    fun previewKeepsSessionIdentifierAndClipsLongMessages() {
        val summary = summarize("session-1", listOf(
            SessionEventRow("session-1", 0, "turn/start", 1, ""),
            SessionEventRow("session-1", 1, "user/message", 2, "abc".repeat(60)),
        ))
        assertEquals("session-1", summary.id)
        assertEquals(2, summary.eventCount)
        assertEquals(80, summary.preview.length)
        assertEquals(2, summary.lastEventTime)
    }
}
